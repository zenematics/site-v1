// Writes zenderal/guide/<id>/index.html for each guide section in src/zenderal/guide/sections.js,
// with its own title and link-preview tags. Run after adding, renaming or re-describing a section:
//   npm run gen:guide
// vite.config.js picks up every folder under zenderal/guide/ as a page.
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { SECTIONS } from '../src/zenderal/guide/sections.js';

const ROOT = resolve(import.meta.dirname, '../zenderal/guide');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

const page = ({ id, title, desc }) => {
  const t = esc(`${title} — Zenderal Guide`);
  const d = esc(desc);
  const url = `https://zenematics.com/zenderal/guide/${id}/`;
  return `<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${t}</title>
    <meta name="description" content="${d}" />
    <link rel="canonical" href="${url}" />
    <meta name="theme-color" content="#07080a" />
    <!-- Link previews (Discord, iMessage, X, etc.). Generated by scripts/gen-guide-pages.mjs. -->
    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="Zenematics" />
    <meta property="og:title" content="${t}" />
    <meta property="og:description" content="${d}" />
    <meta property="og:url" content="${url}" />
    <meta property="og:image" content="https://zenematics.com/uploads/og/zenderal.jpg" />
    <meta property="og:image:width" content="1200" />
    <meta property="og:image:height" content="630" />
    <meta property="og:image:alt" content="Zenderal" />
    <meta name="twitter:card" content="summary_large_image" />
    <link rel="icon" type="image/png" href="/uploads/zen-logo-white.png" />
    <!-- Futura PT via Adobe Fonts; the web project ID lives in .env (VITE_TYPEKIT_ID) -->
    <link rel="stylesheet" href="https://use.typekit.net/%VITE_TYPEKIT_ID%.css" />
  </head>
  <body>
    <div id="root" data-section="${id}"></div>
    <script type="module" src="/src/zenderal-guide.jsx"></script>
  </body>
</html>
`;
};

// Drop pages for sections that no longer exist.
const ids = new Set(SECTIONS.map((s) => s.id));
for (const d of readdirSync(ROOT, { withFileTypes: true })) {
  if (d.isDirectory() && !ids.has(d.name)) rmSync(resolve(ROOT, d.name), { recursive: true });
}

for (const s of SECTIONS) {
  mkdirSync(resolve(ROOT, s.id), { recursive: true });
  writeFileSync(resolve(ROOT, s.id, 'index.html'), page(s));
}
console.log(`Wrote ${SECTIONS.length} guide pages.`);
